# tests/test_r63_a_loc.py -- R6.3 part A, D2a (docs/plans/r6-3-book-content.md): the lines-of-code
# counter. Python by `tokenize` (code, docstring, comment-only, blank); JS, CSS, HTML and Kotlin by
# a comment-aware scanner; each file in one area (source / tests / config / generated; vendored left
# out) under the one module that owns it. Pinned on a fixture against a HAND count (the comments
# beside each text say which line is which).
from __future__ import annotations

from pathlib import Path

import pytest

from jarvis.buildbook.gen import loc
from jarvis.buildbook.gen.repo import Repo

PY = '''"""The module's docstring,
on two lines."""

import os  # a trailing comment is code

# a comment-only line


def f(x: int) -> str:
    """One line of docstring."""
    s = """a string

that is code"""
    return s + str(x)
'''  # the hand count is in test_python_is_counted_by_tokenize_against_a_hand_count
JS = """// a line comment
const a = 'not // a comment';
/* a block
   comment */
const re = /https?:\\/\\//;

const t = `a template
// inside it`;  // after
"""  # code 4 (a, re, t, the template's second line), comment 3, blank 1
CSS = """/* the theme */
.bset { color: red; }

/* one
   two */ .dsc { margin: 0 }
"""  # code 2, comment 2, blank 1
HTML = """<!doctype html>
<!-- a comment -->
<p>hi</p>
<!--
 two -->

"""  # code 2, comment 3, blank 1 (the last line)
KT = """package demo
/* outer /* nested */ still a comment */
val s = "// not a comment"
val raw = \"\"\"
  /* inside a raw string */
\"\"\"
// done
"""  # code 5, comment 2, blank 0
FILES = {
    "src/jarvis/demo/mod.py": PY,
    "src/jarvis/api/static/console-demo.js": JS,
    "src/jarvis/api/static/console-demo.css": CSS,
    "src/jarvis/api/static/book.html": HTML,
    "src/jarvis/api/static/vendor/three.module.js": "const x = 1;\n",  # vendored: left out
    "android/app/src/main/java/demo/Main.kt": KT,
    "tests/test_demo.py": "def test_x() -> None:\n    assert True\n",
    "scripts/tool.py": "# a tool\nprint(1)\n",
    "src/jarvis/demo/gen_table.py": "# @generated by scripts/tool.py: do not edit\nX = 1\n",
    "src/jarvis/demo/broken.py": 'def broken(:\n    """no"""\n# yes\n',
    "docs/readme.md": "not a counted language\n",
}


@pytest.fixture()
def repo(tmp_path: Path) -> Repo:
    for rel, text in FILES.items():
        (tmp_path / rel).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / rel).write_text(text, encoding="utf-8")
    return Repo.from_dir(tmp_path, sha="a" * 40, committed_at="2026-11-24T09:00:00+05:30")


def test_python_is_counted_by_tokenize_against_a_hand_count() -> None:
    got = loc.count_text("x.py", PY)
    # code: import, def, s = (line 1 of the string), "that is code", return = 5; the docstring
    # lines: 2 (module) + 1 (function) = 3; comment-only: 1; blank: 5 (one inside the string: a
    # whitespace-only line is blank wherever it is, as cloc counts it)
    assert (got.code, got.docstring, got.comment, got.blank) == (5, 3, 1, 5)


@pytest.mark.parametrize(
    ("name", "text", "want"),
    [
        ("a.js", JS, (4, 0, 3, 1)),
        ("a.css", CSS, (2, 0, 2, 1)),
        ("a.html", HTML, (2, 0, 3, 1)),
        ("a.kt", KT, (5, 0, 2, 0)),
    ],
)
def test_each_scanner_against_a_hand_count(
    name: str, text: str, want: tuple[int, int, int, int]
) -> None:
    got = loc.count_text(name, text)
    assert (got.code, got.docstring, got.comment, got.blank) == want


def test_a_file_that_isnt_python_falls_back_to_the_hash_scanner() -> None:
    got = loc.count_text("broken.py", FILES["src/jarvis/demo/broken.py"])
    assert (got.code, got.comment, got.blank) == (2, 1, 0)


def test_areas_modules_and_what_is_left_out(repo: Repo) -> None:
    rows = {(r.module, r.area, r.language): r for r in loc.count(repo)}
    assert set(rows) == {
        ("demo", "source", "python"),
        ("demo", "generated", "python"),
        ("api", "source", "javascript"),
        ("api", "source", "css"),
        ("api", "source", "html"),
        ("android", "source", "kotlin"),
        ("tests", "tests", "python"),
        ("scripts", "config", "python"),
    }
    assert rows[("demo", "source", "python")].files == 2  # mod.py and broken.py
    assert rows[("demo", "source", "python")].code == 5 + 2
    assert rows[("api", "source", "javascript")].code == 4  # the vendored file is not counted
    assert loc.python_code(loc.count(repo)) == 7  # source Python under src/ only


def test_the_rows_are_sorted_and_deterministic(repo: Repo) -> None:
    rows = loc.count(repo)
    assert rows == loc.count(repo)
    assert [(r.module, r.area, r.language) for r in rows] == sorted(
        (r.module, r.area, r.language) for r in rows
    )


def test_code_lines_of_one_file(repo: Repo) -> None:
    assert loc.code_lines(repo, "src/jarvis/demo/mod.py") == 5
    assert loc.code_lines(repo, "src/jarvis/api/static/vendor/three.module.js") == 0
    assert loc.code_lines(repo, "docs/readme.md") == 0


@pytest.mark.parametrize(
    ("n", "words"),
    [(124_475, "124 thousand"), (124_500, "125 thousand"), (999, "999"), (1_000, "1 thousand")],
)
def test_thousands_in_words(n: int, words: str) -> None:
    assert loc.in_thousands(n) == words
