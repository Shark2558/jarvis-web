# src/jarvis/buildbook/gen/loc.py
"""R6.3 D2a (docs/plans/r6-3-book-content.md; Phase A G6): the lines-of-code counter. Standard
library only, deterministic, never a raw newline count.

- Python by `tokenize`: a line is code when any token but a comment or a docstring is on it; a
  docstring line when a bare string statement covers it (module, class and function docstrings);
  comment-only; blank (whitespace only, wherever it is, as cloc counts). A file `tokenize`
  refuses is read by the hash-comment scanner instead.
- JavaScript, CSS, HTML and Kotlin by a comment-aware scanner: strings, template literals, JS
  regex literals and Kotlin raw strings are code; `//` and `/* */` (Kotlin's nest) and `<!-- -->`
  are comments.
- Each file is in ONE area: `source`, `tests` (tests/, evals/, Android's test folders), `config`
  (scripts/, tools/, deploy/, .github/, .claude/, Gradle scripts, root files) or `generated` (an
  "@generated" or "do not edit" mark in its first lines); vendored code (`vendor/`,
  `node_modules/`) is left out. Each file under the one module that owns it: its top-level
  package under `src/jarvis/` (the console's static files are `api`'s), else its top folder.

`count(repo)` -> sorted `LineCount` rows; `python_code(rows)` (the tour's `loc.python_code`);
`code_lines(repo, rel)` (the book's package lines, G6); `in_thousands(n)` ("124 thousand").
"""

from __future__ import annotations

import io
import re
import tokenize
from collections import defaultdict
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from functools import lru_cache

from jarvis.buildbook.facts_model import LineCount
from jarvis.buildbook.gen.repo import Repo

LANGUAGES: dict[str, str] = {
    ".py": "python",
    ".js": "javascript",
    ".mjs": "javascript",
    ".css": "css",
    ".html": "html",
    ".kt": "kotlin",
    ".kts": "kotlin",
}
VENDORED = re.compile(r"(?:^|/)(?:vendor|node_modules)/")
TEST_AREAS = ("tests/", "evals/", "android/app/src/test/", "android/app/src/androidTest/")
CONFIG_AREAS = ("scripts/", "tools/", "deploy/", ".github/", ".claude/", "docs/")
GENERATED = re.compile(r"@generated|do not edit|generated by", re.IGNORECASE)
GENERATED_LINES = 5  # where a generated file says so
SRC = "src/jarvis/"
_SKIP = frozenset(
    {
        tokenize.NL,
        tokenize.NEWLINE,
        tokenize.INDENT,
        tokenize.DEDENT,
        tokenize.ENDMARKER,
        tokenize.ENCODING,
    }
)
_STARTS = frozenset({tokenize.NEWLINE, tokenize.INDENT, tokenize.DEDENT, tokenize.NL})
THOUSAND = 1_000
CACHED_FILES = 8_192  # every counted file of the repository, about 2,300 today


@dataclass(frozen=True)
class Counted:
    code: int = 0
    docstring: int = 0
    comment: int = 0
    blank: int = 0


def _tally(lines: Sequence[str], kinds: dict[int, str]) -> Counted:
    """`kinds` maps a 1-based line to "code", "docstring" or "comment". A whitespace-only line is
    blank wherever it is (inside a string too, as cloc counts); a line with text no token covers
    (a lone backslash) is code."""
    got = {"code": 0, "docstring": 0, "comment": 0, "blank": 0}
    for row, line in enumerate(lines, start=1):
        kind = "blank" if not line.strip() else kinds.get(row, "code")
        got[kind] += 1
    return Counted(**got)


def _mark(kinds: dict[int, str], first: int, last: int, kind: str) -> None:
    rank = {"code": 3, "docstring": 2, "comment": 1}
    for row in range(first, last + 1):
        if rank[kind] > rank.get(kinds.get(row, ""), 0):
            kinds[row] = kind


def _python(text: str) -> Counted:
    toks = [t for t in tokenize.generate_tokens(io.StringIO(text).readline)]
    kinds: dict[int, str] = {}
    at_start = True
    for i, tok in enumerate(toks):
        if tok.type == tokenize.COMMENT:
            _mark(kinds, tok.start[0], tok.start[0], "comment")
        elif tok.type not in _SKIP:
            alone = tok.type == tokenize.STRING and at_start and _ends_statement(toks, i + 1)
            _mark(kinds, tok.start[0], tok.end[0], "docstring" if alone else "code")
        at_start = tok.type in _STARTS or (at_start and tok.type == tokenize.COMMENT)
    return _tally(text.splitlines(), kinds)


def _ends_statement(toks: Sequence[tokenize.TokenInfo], i: int) -> bool:
    for tok in toks[i:]:
        if tok.type == tokenize.COMMENT:
            continue
        return tok.type in (tokenize.NEWLINE, tokenize.ENDMARKER)
    return True


def _hashes(text: str) -> Counted:
    lines = text.splitlines()
    kinds = {n: "comment" for n, ln in enumerate(lines, 1) if ln.lstrip().startswith("#")}
    return _tally(lines, kinds)


@dataclass(frozen=True)
class _Syntax:
    line: str = "//"
    block: tuple[str, str] = ("/*", "*/")
    nests: bool = False
    quotes: str = "\"'`"
    raw: str = ""  # Kotlin's """...""" (no escapes)
    regex: bool = False  # JavaScript's /.../ literals


SYNTAX: dict[str, _Syntax] = {
    "javascript": _Syntax(regex=True),
    "css": _Syntax(line="", quotes="\"'"),
    "html": _Syntax(line="", block=("<!--", "-->"), quotes=""),
    "kotlin": _Syntax(nests=True, quotes="\"'", raw='"""'),
}
_REGEX_BEFORE = frozenset("(,=:[!&|?{};+-*%<>~^")


class _Scan:
    """One pass over a C-like text: each character's line marked code or comment."""

    def __init__(self, text: str, syntax: _Syntax) -> None:
        self.text, self.s, self.i, self.row = text, syntax, 0, 1
        self.kinds: dict[int, str] = {}
        self.last = ""  # the last code character (a JS regex follows an operator)

    def run(self) -> dict[int, str]:
        while self.i < len(self.text):
            if not self._comment() and not self._string():
                self._char("code")
        return self.kinds

    def _char(self, kind: str) -> None:
        ch = self.text[self.i]
        if ch == "\n":
            self.row += 1
        elif not ch.isspace():
            _mark(self.kinds, self.row, self.row, kind)
            if kind == "code":
                self.last = ch
        self.i += 1

    def _upto(self, end: str, kind: str, *, escapes: bool) -> None:
        while self.i < len(self.text) and not self.text.startswith(end, self.i):
            if escapes and self.text[self.i] == "\\" and self.i + 1 < len(self.text):
                self._char(kind)
            self._char(kind)
        for _ in end:
            if self.i < len(self.text):
                self._char(kind)

    def _comment(self) -> bool:
        s, t, i = self.s, self.text, self.i
        if s.line and t.startswith(s.line, i):
            self._upto("\n", "comment", escapes=False)
            return True
        if not t.startswith(s.block[0], i):
            return False
        depth = 0
        while self.i < len(t):
            if t.startswith(s.block[0], self.i) and (s.nests or depth == 0):
                depth += 1
                for _ in s.block[0]:
                    self._char("comment")
            elif t.startswith(s.block[1], self.i):
                depth -= 1
                for _ in s.block[1]:
                    self._char("comment")
                if depth == 0:
                    break
            else:
                self._char("comment")
        return True

    def _string(self) -> bool:
        t, i = self.text, self.i
        if self.s.raw and t.startswith(self.s.raw, i):
            for _ in self.s.raw:
                self._char("code")
            self._upto(self.s.raw, "code", escapes=False)
            return True
        quote = t[i]
        regex = self.s.regex and quote == "/" and (self.last in _REGEX_BEFORE or not self.last)
        if quote not in self.s.quotes and not regex:
            return False
        self._char("code")
        self._upto(quote, "code", escapes=True)
        return True


@lru_cache(maxsize=CACHED_FILES)
def count_text(name: str, text: str) -> Counted:
    """The counts of one file's text, by its name's language (zero for anything else). Kept by
    (name, text): `--check`'s second build and the book's package lines reuse the first count."""
    language = language_of(name)
    if language == "python":
        try:
            return _python(text)
        except (tokenize.TokenError, IndentationError, SyntaxError):
            return _hashes(text)
    if language in SYNTAX:
        return _tally(text.splitlines(), _Scan(text, SYNTAX[language]).run())
    return Counted()


def language_of(rel: str) -> str | None:
    dot = rel.rfind(".")
    return LANGUAGES.get(rel[dot:]) if dot > rel.rfind("/") else None


def area_of(rel: str, text: str) -> str | None:
    """The file's area; None when it is not counted (vendored, or no counted language)."""
    if language_of(rel) is None or VENDORED.search(rel):
        return None
    if GENERATED.search("\n".join(text.splitlines()[:GENERATED_LINES])):
        return "generated"
    if rel.startswith(TEST_AREAS):
        return "tests"
    if rel.startswith(CONFIG_AREAS) or "/" not in rel or rel.endswith(".kts"):
        return "config"
    return "source"


def module_of(rel: str) -> str:
    if rel.startswith(SRC):
        head = rel[len(SRC) :].split("/", 1)[0]
        return head[:-3] if head.endswith(".py") else head
    return rel.split("/", 1)[0] if "/" in rel else "repository"


def code_lines(repo: Repo, rel: str) -> int:
    """The code lines of one tracked file (0: vendored, not text, or not a counted language)."""
    text = repo.text(rel)
    if text is None or area_of(rel, text) is None:
        return 0
    return count_text(rel, text).code


def count(repo: Repo) -> tuple[LineCount, ...]:
    sums: dict[tuple[str, str, str], list[int]] = defaultdict(lambda: [0, 0, 0, 0, 0])
    for rel in repo.files:
        text = repo.text(rel) if language_of(rel) else None
        area = area_of(rel, text) if text is not None else None
        if text is None or area is None:
            continue
        got = count_text(rel, text)
        row = sums[(module_of(rel), area, str(language_of(rel)))]
        for k, n in enumerate((1, got.code, got.docstring, got.comment, got.blank)):
            row[k] += n
    return tuple(_row(key, sums[key]) for key in sorted(sums))


def _row(key: tuple[str, str, str], n: list[int]) -> LineCount:
    module, area, language = key
    return LineCount.model_validate(
        {
            "module": module,
            "area": area,
            "language": language,
            "files": n[0],
            "code": n[1],
            "docstring": n[2],
            "comment": n[3],
            "blank": n[4],
        }
    )


def python_code(rows: Iterable[LineCount]) -> int:
    """Python code lines of the source area (what `src/` holds: nothing else is source Python)."""
    return sum(r.code for r in rows if r.language == "python" and r.area == "source")


def in_thousands(n: int) -> str:
    """124,475 -> "124 thousand" (half up); under a thousand, the number itself."""
    if n < THOUSAND:
        return str(n)
    return f"{(n + THOUSAND // 2) // THOUSAND} thousand"


